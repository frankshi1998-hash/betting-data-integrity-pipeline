    select *
    from {{ source('raw', 'bookmaker_bet_dump') }}
)

select
    ingestion_id,
    source_file,
    source_sheet,
    source_row_number,
    ingested_at,
    {{ clean_text('refid') }} as source_refid,
    {{ clean_text('source_uuid') }} as source_uuid,
    {{ clean_text('license') }} as license,
    {{ clean_text('bookmaker') }} as bookmaker_name,
    {{ clean_text('location') }} as location_name,
    {{ clean_text('state') }} as state_code,
    {{ clean_text('area') }} as area_name,
    {{ clean_text('wagering_provider') }} as wagering_provider,
    {{ clean_text('sys_ver_no') }} as system_version,
    {{ parse_source_timestamp('bet_date', 'bet_time') }} as bet_placed_at,
    {{ parse_source_timestamp('event_date', 'event_time') }} as event_scheduled_at,
    {{ clean_text('ticket_no') }} as ticket_no,
    {{ clean_text('event_category') }} as event_category,
    {{ clean_text('sport_event') }} as sport_event_name,
    {{ clean_text('venue') }} as venue_name,
    {{ clean_text('venue_state') }} as venue_state_code,
