    {{ clean_text('bet_method') }} as bet_method,
    {{ clean_text('bet_details') }} as bet_details,
    {{ parse_integer('race_number') }} as race_number,
    {{ parse_integer('runner_number') }} as runner_number,
    {{ clean_text('runner_name') }} as runner_name,
    {{ parse_money('bet_amount_win') }} as stake_win_amount,
    {{ parse_money('bet_amount_place') }} as stake_place_amount,
    coalesce({{ parse_money('bet_amount_win') }}, 0) + coalesce({{ parse_money('bet_amount_place') }}, 0) as total_stake_amount,
    {{ parse_decimal('win_price') }} as win_price,
    {{ parse_decimal('place_price') }} as place_price,
    {{ clean_text('customer_name') }} as customer_name,
    {{ clean_text('betback_claim') }} as betback_claim,
    {{ clean_text('bet_information') }} as bet_information,
    {{ parse_boolean_flag('cancelled_flag') }} as is_cancelled,
    {{ parse_source_timestamp('bet_date', 'time_cancelled') }} as cancelled_at,
    {{ parse_decimal('bet_win_takeout') }} as bet_win_takeout,
    {{ parse_decimal('bet_place_takeout') }} as bet_place_takeout,
    {{ parse_decimal('horse_win_takeout') }} as horse_win_takeout,
    {{ parse_decimal('horse_win_hold') }} as horse_win_hold,
    {{ parse_decimal('horse_place_takeout') }} as horse_place_takeout,
    {{ parse_decimal('horse_place_hold') }} as horse_place_hold,
    {{ parse_decimal('race_hold') }} as race_hold,
    {{ clean_text('betback_information') }} as betback_information,
    {{ parse_boolean_flag('betback_flag') }} as is_betback,
    {{ parse_boolean_flag('refund_flag') }} as is_refunded,
    {{ parse_integer('placing_position') }} as placing,
    {{ parse_decimal('win_deduction') }} as win_deduction,
    {{ parse_decimal('place_deduction') }} as place_deduction,
    {{ parse_decimal('win_result') }} as win_result,
    {{ parse_decimal('place_result') }} as place_result,
    {{ parse_money('win_payout_amount') }} as win_payout_amount,
    {{ parse_money('place_payout_amount') }} as place_payout_amount,
    coalesce({{ parse_money('win_payout_amount') }}, 0) + coalesce({{ parse_money('place_payout_amount') }}, 0) as total_payout_amount,
    {{ clean_text('paid_status') }} as paid_status,
    {{ clean_text('bet_terminal') }} as bet_terminal,
    raw_payload,
    case when {{ clean_text('refid') }} is null then true else false end as missing_refid_flag,
    case when {{ parse_money('bet_amount_win') }} is null and {{ parse_money('bet_amount_place') }} is null then true else false end as missing_stake_flag,
    case when coalesce({{ parse_money('bet_amount_win') }}, 0) + coalesce({{ parse_money('bet_amount_place') }}, 0) < 0 then true else false end as negative_stake_flag
